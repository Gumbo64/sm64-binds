#!/usr/bin/env python3
"""Builds the portable save state translator (rust/portable-wasm) and writes it
as a JS module, javascript/src/scripts/sm64/pkg/portable_wasm.js, so the
JavaScript package can load it without a bundler asset.

    python3 maketools/portable_wasm.py

Needs the `wasm32-unknown-unknown` Rust target. `wasm-opt` (from binaryen or
emsdk) shrinks it further when found. Run `maketools/gen_portable_tables.py`
first when the game was rebuilt: the tables are compiled into the module.
"""

import base64
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
CRATE = os.path.join(ROOT, "rust", "portable-wasm")
OUT = os.path.join(ROOT, "javascript", "src", "scripts", "sm64", "pkg", "portable_wasm.js")


def main():
    subprocess.run(["cargo", "build", "--release", "--target", "wasm32-unknown-unknown"], cwd=CRATE, check=True)
    wasm = os.path.join(CRATE, "target", "wasm32-unknown-unknown", "release", "sm64_portable_wasm.wasm")
    emsdk = os.environ.get("EMSDK", "/usr/local/emsdk")
    opt = shutil.which("wasm-opt") or os.path.join(emsdk, "upstream", "bin", "wasm-opt")
    if os.path.exists(opt):
        out = wasm + ".opt"
        subprocess.run([opt, "-Oz", "--enable-bulk-memory", "--enable-nontrapping-float-to-int",
                        "--enable-sign-ext", "--enable-mutable-globals", wasm, "-o", out], check=True)
        wasm = out
    data = open(wasm, "rb").read()
    with open(OUT, "w") as f:
        f.write("// Generated by maketools/portable_wasm.py from rust/portable-wasm. Do not edit.\n")
        f.write(f"// {len(data)} bytes of WASM.\n")
        f.write("export const PORTABLE_WASM_BASE64 =\n  \"" + base64.b64encode(data).decode() + "\";\n")
    print(f"{len(data)} bytes -> {OUT}")


if __name__ == "__main__":
    sys.exit(main())
